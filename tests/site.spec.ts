import { test, expect } from '@playwright/test'

test('home has separate cards and localized complete articles', async ({ page }) => {
  await page.goto('/pt/')
  await expect(page.locator('.gist-card')).toHaveCount(2)
  await expect(page.locator('.post-row')).toHaveCount(3)
  await page.locator('.post-row').filter({ hasText: 'Montessori' }).click()
  await expect(page.locator('.article-copy img')).toHaveCount(12)
  await expect(page.locator('.article-copy a[href$=".stl"]')).toHaveCount(2)
  await page.locator('.locale-toggle a').click()
  await expect(page).toHaveURL(/\/en\/posts\//)
  await expect(page.locator('h1')).toHaveText('Building a 4-in-1 Montessori Learning Tower')
})

test('mobile navigation, keyboard dismissal, and persistent theme', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/pt/')
  const menu = page.locator('.mobile-menu')
  await menu.click()
  await expect(menu).toHaveAttribute('aria-expanded', 'true')
  await expect(page.locator('.tree-list')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(menu).toHaveAttribute('aria-expanded', 'false')
  await page.locator('.theme-switch').click()
  const theme = await page.locator('html').getAttribute('data-color-mode')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-color-mode', theme!)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('navigation and content remain available without JavaScript', async ({ browser }) => {
  const context = await browser.newContext({ javaScriptEnabled: false, viewport: { width: 390, height: 844 } })
  const page = await context.newPage()
  await page.goto('http://localhost:4322/en/')
  await expect(page.locator('.sidebar-nav')).toBeVisible()
  await page.locator('.post-row').first().click()
  await expect(page.locator('.article-copy')).toBeVisible()
  await context.close()
})

test('STL previews keep their downloads and show a pan cursor', async ({ page, browser }) => {
  const article = '/en/posts/building-a-4-in-1-montessori-learning-tower/'
  await page.goto(article)
  const viewer = page.locator('stl-viewer').first()
  await viewer.scrollIntoViewIfNeeded()
  await expect(viewer.locator('canvas')).toBeVisible()
  await expect(viewer.locator('canvas')).toHaveCSS('cursor', 'grab')
  const canvas = viewer.locator('canvas')
  await canvas.hover()
  await page.mouse.down()
  await expect(canvas).toHaveCSS('cursor', 'grabbing')
  await page.mouse.up()
  await expect(viewer.locator('a[download]')).toHaveAttribute('href', /\.stl$/)

  const noScript = await browser.newContext({ javaScriptEnabled: false })
  const noScriptPage = await noScript.newPage()
  await noScriptPage.goto(`http://localhost:4322${article}`)
  await expect(noScriptPage.locator('stl-viewer a[download]')).toHaveCount(2)
  await noScript.close()
})

test('article images open and close a keyboard-accessible zoom', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/pt/posts/construindo-uma-torre-de-aprendizagem-montessori-4-em-1/')
  const image = page.locator('.article-copy img').first()
  await image.scrollIntoViewIfNeeded()
  await expect(image).toHaveCSS('cursor', 'zoom-in')
  await image.focus()
  await page.keyboard.press('Enter')

  const dialog = page.locator('.image-zoom-dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog).toBeFocused()
  await expect(dialog.locator('img')).toHaveAttribute('src', /montessori-tower-finished-01\.png$/)
  expect(await dialog.evaluate(element => element.getBoundingClientRect().width <= innerWidth)).toBe(true)
  await page.mouse.wheel(0, 500)
  await expect(dialog).not.toBeVisible()

  await image.click()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(image).toBeFocused()

  await image.click()
  await dialog.locator('img').click()
  await expect(dialog).not.toBeVisible()
  await image.click()
  await page.mouse.click(5, 5)
  await expect(dialog).not.toBeVisible()

  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/en/posts/how-i-built-my-blog-with-quartz/')
  const markdownImage = page.locator('.article-copy img').first()
  await expect(markdownImage).toHaveAttribute('role', 'button')
  const thumbnailWidth = await markdownImage.evaluate(element => element.getBoundingClientRect().width)
  await markdownImage.click()
  const zoomedWidth = await dialog.locator('img').evaluate(element => element.getBoundingClientRect().width)
  expect(zoomedWidth).toBeGreaterThan(thumbnailWidth)
})
